#!/usr/bin/env python3
"""Regenerate INDEX.md in the idea bank from each idea file's frontmatter.

usage: index.py BANK_DIR
"""
import glob, os, re, sys

ORDER = ["founder-conversations", "community", "inside-pally", "frontier-tech", "ai-workflow"]
STATUS_ORDER = {"drafting": 0, "idea": 1, "posted": 2, "dropped": 3}


def frontmatter(path):
    text = open(path, errors="replace").read()
    m = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not m:
        return {}, text
    meta, key = {}, None
    for line in m.group(1).splitlines():
        if re.match(r"^\s+- ", line) and key:
            meta.setdefault(key, []).append(line.strip()[2:])
        elif ":" in line and not line.startswith(" "):
            key, val = line.split(":", 1)
            key = key.strip()
            val = re.sub(r"\s+#.*$", "", val).strip()
            meta[key] = val if val else []
    return meta, m.group(2)


def main():
    bank = sys.argv[1]
    rows = {}
    for f in glob.glob(os.path.join(bank, "ideas", "*", "*.md")):
        meta, body = frontmatter(f)
        hook = re.search(r"\*\*Hook:\*\*\s*(.+)", body)
        pillar = meta.get("pillar") or os.path.basename(os.path.dirname(f))
        rows.setdefault(pillar, []).append({
            "title": meta.get("title") or os.path.basename(f)[:-3],
            "status": meta.get("status") or "idea",
            "updated": meta.get("updated") or meta.get("added") or "",
            "sources": len(meta.get("sources") or []),
            "hook": (hook.group(1).strip() if hook else "").replace("|", "\\|")[:140],
            "path": os.path.relpath(f, bank),
        })
    total = sum(len(v) for v in rows.values())
    live = sum(1 for v in rows.values() for r in v if r["status"] in ("idea", "drafting"))
    out = ["# Idea index", "",
           f"{total} ideas, {live} open. Generated by `index.py`; edit the idea files, not this page.", ""]
    for pillar in ORDER + sorted(set(rows) - set(ORDER)):
        if pillar not in rows:
            continue
        out += [f"## {pillar} ({len(rows[pillar])})", "",
                "| Idea | Status | Updated | Sources | Hook |", "|---|---|---|---|---|"]
        for r in sorted(rows[pillar], key=lambda r: (STATUS_ORDER.get(r["status"], 9), r["updated"]), reverse=False):
            out.append(f"| [{r['title']}]({r['path']}) | {r['status']} | {r['updated']} | {r['sources']} | {r['hook']} |")
        out.append("")
    with open(os.path.join(bank, "INDEX.md"), "w") as fh:
        fh.write("\n".join(out))
    print(f"{total} ideas indexed")


if __name__ == "__main__":
    main()
